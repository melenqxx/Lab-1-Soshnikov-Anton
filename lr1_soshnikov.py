import os
from time import sleep


RED = '\u001b[41m'      # красный ФОН 
GREEN = '\u001b[42m'    # зелёный фон
BLUE = '\u001b[44m'     # синий фон
WHITE = '\u001b[47m'    # белый фон
BLACK = '\u001b[40m'    # чёрный фон
RESET = '\u001b[0m'     # сбросить цвет

# строчка чтобы escape-символы заработали
os.system('')


# ф-я, которая очищает консоль
# В вин команда cls
# os.name == 'nt' значит, что у меня вин
def clear():
    if os.name == 'nt':
        os.system('cls')
    else:
        os.system('clear')


# Флаг Бангладеш
# зеленый прямоугольник и красный круг внутри
def draw_flag():
    height = 18         # высота флага в строках
    length = 60         # ширина флага в символах
    center_x = 27       # где по горизонтали центр круга
    center_y = 9        # где по вертикали центр круга
    radius = 6          # радиус круга

    # иду по каждой строке сверху вниз
    for y in range(height):
        line = ''       # сюда буду собирать строку из цветных пробелов

        # иду по каждой клетке в строке слева направо
        for x in range(length):
            # считаю, как далеко клетка от центра круга.
            # по горизонтали делю на 2, потому что символ в консоли
            # в 2 раза выше, чем шире. иначе круг будет овалом.
            dx = (x - center_x) / 2
            dy = y - center_y

            # формула круга: dx^2 + dy^2 <= r^2
            # если это верно, значит клетка внутри круга
            if dx * dx + dy * dy <= radius * radius:
                line = line + RED + ' '      # красный пробел
            else:
                line = line + GREEN + ' '    # зелёный пробел

        # RESET в конце строки, чтобы цвет не "вытекал" дальше
        print(line + RESET)


# повторяющийся узор 
# рисую маленький кусочек (плитку), потом повторяю его много раз
# '#' - чёрная клетка, '.' - белая клетка
TILE = [
    '#####.',
    '#...#.',
    '#.###.',
    '#.#...',
    '#.####',
    '......',
]


def draw_pattern():
    # повторяю плитку 3 раза вниз
    for _ in range(3):
        # иду по строкам плитки
        for row in TILE:
            line = ''
            # повторяю строку плитки 8 раз вправо
            for _ in range(8):
                # иду по символам в строке плитки
                for ch in row:
                    if ch == '#':
                        line = line + BLACK + '  '   # чёрная клетка (2 пробела, чтобы была квадратной)
                    else:
                        line = line + WHITE + '  '   # белая клетка
            print(line + RESET)


# анимация из 4 кадров
# красный блок двигается вправо
def animation():
    # весь цикл из 4 кадров повторяю 3 раза, чтобы было подольше
    for _ in range(4):
        # 4 кадра
        for frame in range(4):
            clear()                       # стираю предыдущий кадр
            print('Кадр', frame + 1)      # frame идёт с 0, поэтому +1

            # на сколько символов сдвинуть блок вправо
            shift = frame * 10

            # рисую блок высотой 3 строки
            for _ in range(3):
                # \u001b[nC двигает курсор вправо на n символов
                # потом рисую 6 красных пробелов
                print(f'\u001b[{shift}C' + RED + ' ' * 6 + RESET)

            sleep(0.5)      # пауза полсекунды, чтобы успеть увидеть кадр
    clear()



# диаграмма из файла sequence.txt
# считаю сумму по модулю первых 125 и вторых 125 чисел
# показываю, сколько процентов приходится на каждую сумму
def diagram():
    # ищу файл в той же папке, где лежит мой скрипт
    # __file__  путь к моему скрипту, dirname берёт из него папку
    folder = os.path.dirname(os.path.abspath(__file__))
    path = os.path.join(folder, 'sequence.txt')

    # открываю файл и читаю все числа
    # split() режет текст на кусочки по пробелам и переносам строк
    # float() превращает каждый кусочек из текста в число
    # replace(',', ' ') на случай, если числа записаны через запятую
    with open(path) as f:
        numbers = [float(x) for x in f.read().replace(',', ' ').split()]

    # numbers[:125] - первые 125 чисел
    # numbers[125:250] - числа с 126 по 250
    # abs() - модуль числа (без минуса)
    first = sum(abs(n) for n in numbers[:125])
    second = sum(abs(n) for n in numbers[125:250])

    # сколько процентов составляет первая сумма от общей
    percent1 = first / (first + second) * 100
    # вторая - это всё остальное, вместе должно быть ровно 100%
    percent2 = 100 - percent1

    # рисую полоску длиной 50 символов
    width = 50
    len1 = round(percent1 / 100 * width)    # сколько символов синих
    len2 = width - len1                     # остальные красные

    print(BLUE + ' ' * len1 + RED + ' ' * len2 + RESET)
    print(BLUE + '  ' + RESET, f'первые 125:  {first:.2f}  ({percent1:.1f}%)')
    print(RED + '  ' + RESET, f'вторые 125:  {second:.2f}  ({percent2:.1f}%)')



# вызываю все по порядку

draw_flag()
